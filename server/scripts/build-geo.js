// Builds website/js/world-geo.js: every country with its cities, for the registration form.
// Data: countries-list (MIT) and city-timezones (MIT, Natural Earth cities).
// Run: npm run build-geo
const fs = require("fs");
const path = require("path");
const { countries } = require("countries-list");
const { cityMapping } = require("city-timezones");

// cities where we have chapters / big Telugu communities – shown first
const PRIORITY = {
  US: ["Dallas", "San Francisco Bay Area", "New Jersey", "Chicago", "Atlanta", "New York", "Houston", "Austin", "Seattle", "Los Angeles", "Boston", "Washington DC", "Charlotte", "Raleigh", "Detroit", "Phoenix"],
  CA: ["Toronto", "Vancouver", "Calgary", "Montreal", "Ottawa"],
  GB: ["London", "Manchester", "Birmingham", "Leicester", "Leeds"],
  IE: ["Dublin"], DE: ["Frankfurt", "Munich", "Berlin"], NL: ["Amsterdam"],
  AE: ["Dubai", "Abu Dhabi", "Sharjah"], QA: ["Doha"], KW: ["Kuwait City"], SA: ["Riyadh", "Jeddah", "Dammam"],
  OM: ["Muscat"], BH: ["Manama"], SG: ["Singapore"], MY: ["Kuala Lumpur"], JP: ["Tokyo"],
  AU: ["Sydney", "Melbourne", "Brisbane", "Perth"], NZ: ["Auckland"], ZA: ["Johannesburg"]
};
const SHORT = { US: "USA", GB: "United Kingdom", AE: "UAE" }; // names used across the site

const out = {};
for (const [code, c] of Object.entries(countries)) {
  if (code === "IN") continue; // NRI = living outside India
  const names = cityMapping.filter((x) => x.iso2 === code).sort((a, b) => b.pop - a.pop).map((x) => x.city);
  const first = PRIORITY[code] || [];
  const rest = [...new Set(names)].filter((n) => !first.includes(n)).sort((a, b) => a.localeCompare(b));
  out[code] = { n: SHORT[code] || c.name, p: c.phone[0] ? "+" + c.phone[0] : "", c: [...first, ...rest] };
}
const sorted = Object.fromEntries(Object.entries(out).sort((a, b) => a[1].n.localeCompare(b[1].n)));
const file = path.join(__dirname, "..", "..", "website", "js", "world-geo.js");
fs.writeFileSync(file, "/* generated by server/scripts/build-geo.js – countries-list (MIT), city-timezones (MIT) */\nconst WORLD_GEO = " + JSON.stringify(sorted) + ";\n");
console.log(Object.keys(sorted).length + " countries, " + Object.values(sorted).reduce((s, x) => s + x.c.length, 0) + " cities → " + (fs.statSync(file).size / 1024).toFixed(0) + " KB");
